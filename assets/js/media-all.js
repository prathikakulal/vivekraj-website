document.addEventListener("DOMContentLoaded", () => {
  const hash = window.location.hash.replace("#", "");
  const validTabs = ["en", "kn", "online", "events"];
  if (validTabs.includes(hash)) {
    currentLang = hash;
  }
  renderAllCards();
  updateButtonStyles(currentLang);
});